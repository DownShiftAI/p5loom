#!/usr/bin/env node
// Builds the p5loom website into a static folder, and checks it.
//
//   node scripts/build-docs.mjs                 build into dist/
//   node scripts/build-docs.mjs --out <dir>     build somewhere else
//   node scripts/build-docs.mjs --check         build into a temp folder and run every check (exit 1 on failure)
//
// No dependencies. The site is plain HTML, CSS and ES modules; the library is copied in as /lib/ so the
// playground and the docs run exactly the code the package ships.

import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, copyFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { THEMES, TOKENS } from "../src/theme.js";
import { DARK, LIGHT } from "../site/brand.mjs";
import { validateSpec } from "../src/spec.js";
import { buildPlan } from "../src/plan.js";
import { PAGES, NOT_FOUND, SECTIONS, DOCS } from "../site/content.mjs";
import { EXAMPLES } from "../site/examples.mjs";
import { renderPage, SITE } from "../site/layout.mjs";
import { assertSketch, sketchFrameDocument } from "../src/sketch.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const SITE_DIR = join(root, "site");
const SRC_DIR = join(root, "src");
const EXAMPLE_DIR = join(root, "examples");
const ASSET_DIR = join(SITE_DIR, "assets");
const SKETCH_DIR = join(root, "examples", "sketches");

// ---------- output ----------

function write(out, rel, text) {
  const file = join(out, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text, "utf8");
}

function tokensCss() {
  // Dawnshift tokens (site/brand.mjs). Dark is the default; the system setting picks light unless the reader chose.
  const vars = (t) => Object.entries(t).map(([k, v]) => `--${k}: ${v};`).join(" ");
  const lines = [
    "/* Generated by scripts/build-docs.mjs from site/brand.mjs and src/theme.js. Do not edit by hand. */",
    `:root, :root:not([data-theme="light"]) { color-scheme: dark; ${vars(DARK)} }`,
    `@media (prefers-color-scheme: light) { :root:not([data-theme="dark"]) { color-scheme: light; ${vars(LIGHT)} } }`,
    `:root[data-theme="light"] { color-scheme: light; ${vars(LIGHT)} }`,
    `:root[data-theme="dark"] { color-scheme: dark; ${vars(DARK)} }`,
    // Swatches for the library palettes shown in the docs.
  ];
  for (const [name, t] of Object.entries(THEMES)) {
    for (const k of TOKENS) lines.push(`.sw-${name}-${k} { background: ${t[k]}; }`);
  }
  return lines.join("\n") + "\n";
}

const ICON = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="p5loom">
  <rect width="64" height="64" rx="14" fill="${THEMES.light.bg}"/>
  <circle cx="32" cy="32" r="16" fill="${THEMES.light.accent}"/>
  <circle cx="32" cy="32" r="24" fill="none" stroke="${THEMES.light.fg}" stroke-width="2"/>
</svg>
`;

function listFiles(dir, filter = () => true) {
  return readdirSync(dir)
    .filter((f) => statSync(join(dir, f)).isFile() && filter(f))
    .sort();
}

export function buildSite({ out }) {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  const pages = [...PAGES, NOT_FOUND];
  for (const page of pages) {
    const html = renderPage({
      title: page.title,
      description: page.description,
      path: page.path,
      body: page.body,
      sections: SECTIONS,
      docs: DOCS,
      demos: Boolean(page.demos),
      modules: page.modules ?? [],
    });
    const rel = page.path === "/" ? "index.html" : page.path.replace(/^\//, "");
    write(out, rel, html);
  }

  write(out, "assets/tokens.css", tokensCss());
  for (const f of listFiles(ASSET_DIR)) copyFileSync(join(ASSET_DIR, f), join(out, "assets", f));
  // Self-hosted fonts (scripts/fetch-fonts.mjs writes them into site/assets/fonts).
  if (existsSync(join(ASSET_DIR, "fonts"))) {
    mkdirSync(join(out, "assets", "fonts"), { recursive: true });
    for (const f of listFiles(join(ASSET_DIR, "fonts"), (n) => n.endsWith(".woff2"))) {
      copyFileSync(join(ASSET_DIR, "fonts", f), join(out, "assets", "fonts", f));
    }
  }
  write(out, "assets/icon.svg", ICON);

  // Code mode: each sketch file gets a frame page beside it. The frame loads p5 and the sketch from this origin, so
  // no inline script is needed and the site's policy stays strict.
  write(out, "sketches/frame.css", readFileSync(join(ASSET_DIR, "frame.css"), "utf8"));
  if (existsSync(SKETCH_DIR)) {
    for (const f of listFiles(SKETCH_DIR, (n) => n.endsWith(".js"))) {
      const name = f.replace(/\.js$/, "");
      const code = readFileSync(join(SKETCH_DIR, f), "utf8");
      assertSketch(code);
      write(out, `sketches/${name}/sketch.js`, code);
      write(out, `sketches/${name}/index.html`, sketchFrameDocument({ title: name, scriptUrl: `/sketches/${name}/sketch.js`, theme: "dark" }));
    }
  }

  // The library, as shipped. Every file in src/ is copied flat so its relative imports still resolve.
  for (const f of listFiles(SRC_DIR, (n) => n.endsWith(".js"))) {
    mkdirSync(join(out, "lib"), { recursive: true });
    copyFileSync(join(SRC_DIR, f), join(out, "lib", f));
  }

  // Examples: each spec as JSON, plus the index the playground reads for its picker.
  for (const e of EXAMPLES) {
    mkdirSync(join(out, "examples"), { recursive: true });
    copyFileSync(join(EXAMPLE_DIR, `${e.id}.json`), join(out, "examples", `${e.id}.json`));
  }
  write(
    out,
    "examples/index.json",
    JSON.stringify(EXAMPLES.map(({ id, title, summary }) => ({ id, title, summary })), null, 2) + "\n",
  );

  // The JSON Schema for the spec, at the address its $id names, so editors can fetch it.
  mkdirSync(join(out, "schema"), { recursive: true });
  copyFileSync(join(root, "schema", "p5loom-spec-1.schema.json"), join(out, "schema", "p5loom-spec-1.schema.json"));
  const urls = pages.filter((p) => p.path !== "/404.html").map((p) => `${SITE}${p.path}`);
  write(
    out,
    "sitemap.xml",
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
      .map((u) => `  <url><loc>${u}</loc></url>`)
      .join("\n")}\n</urlset>\n`,
  );
  write(out, "robots.txt", `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`);

  return { pages: pages.map((p) => p.path), out };
}

// ---------- checks ----------

function htmlFiles(dir) {
  const found = [];
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name.endsWith(".html")) found.push(p);
    }
  };
  walk(dir);
  return found;
}

// Maps a root-relative URL path to the file it must be. Returns null when it does not exist.
function fileFor(out, urlPath) {
  const clean = urlPath.replace(/\/+$/, "") || "/";
  const candidates = clean === "/" ? ["index.html"] : [clean.replace(/^\//, ""), clean.replace(/^\//, "") + "/index.html"];
  for (const c of candidates) {
    const p = join(out, c);
    if (existsSync(p) && statSync(p).isFile()) return p;
  }
  return null;
}

export function checkSite(out) {
  const problems = [];
  const files = htmlFiles(out);
  const idsByFile = new Map();
  for (const f of files) idsByFile.set(f, new Set([...readFileSync(f, "utf8").matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])));

  for (const file of files) {
    const rel = relative(out, file).split(sep).join("/");
    const html = readFileSync(file, "utf8");

    // Head metadata every page needs.
    if (!/<title>[^<]+<\/title>/.test(html)) problems.push(`${rel}: missing <title>`);
    if (!/<meta name="description" content="[^"]+">/.test(html)) problems.push(`${rel}: missing meta description`);

    // Content-Security-Policy: no inline script, no inline style, no inline event handlers.
    for (const m of html.matchAll(/<script\b[^>]*>/g)) {
      if (!/\ssrc="/.test(m[0])) problems.push(`${rel}: inline <script> (the CSP forbids it)`);
    }
    if (/\sstyle="/.test(html)) problems.push(`${rel}: inline style attribute (the CSP forbids it)`);
    if (/\son[a-z]+="/i.test(html)) problems.push(`${rel}: inline event handler attribute`);

    // Every internal link and asset must resolve, and every fragment must name an element on its page.
    for (const m of html.matchAll(/\s(?:href|src)="([^"]+)"/g)) {
      const target = m[1];
      if (/^(https?:|mailto:|tel:|#$)/.test(target)) continue;
      if (target.startsWith("//")) {
        problems.push(`${rel}: protocol-relative link ${target}`);
        continue;
      }
      if (!target.startsWith("/") && !target.startsWith("#")) {
        // Relative links are a mistake here: pages are served from the root.
        problems.push(`${rel}: relative link "${target}" (use a root path)`);
        continue;
      }
      const [pathPart, frag] = target.split("#");
      const urlPath = pathPart.split("?")[0];
      let targetFile = file;
      if (urlPath) {
        targetFile = fileFor(out, urlPath);
        if (!targetFile) {
          problems.push(`${rel}: broken link ${target}`);
          continue;
        }
      }
      // Fragments that are state (#example=..., #spec=...) are read by a script, not an anchor.
      if (frag && !frag.includes("=") && frag.length) {
        const ids = idsByFile.get(targetFile) ?? new Set();
        if (!ids.has(frag)) problems.push(`${rel}: fragment #${frag} not found on ${urlPath || rel}`);
      }
    }

    // Demo slots must name a real example.
    for (const m of html.matchAll(/data-demo="([^"]+)"/g)) {
      if (!EXAMPLES.some((e) => e.id === m[1])) problems.push(`${rel}: demo "${m[1]}" has no example`);
    }
  }

  // Examples: valid, and drawable into a plan.
  for (const e of EXAMPLES) {
    const path = join(EXAMPLE_DIR, `${e.id}.json`);
    if (!existsSync(path)) {
      problems.push(`example ${e.id}: no file at site/examples/${e.id}.json`);
      continue;
    }
    let spec;
    try {
      spec = JSON.parse(readFileSync(path, "utf8"));
    } catch (err) {
      problems.push(`example ${e.id}: not JSON (${err.message})`);
      continue;
    }
    const found = validateSpec(spec);
    if (found.length) problems.push(`example ${e.id}: ${found.join("; ")}`);
    else buildPlan(spec);
    if (!e.teaches?.length) problems.push(`example ${e.id}: says nothing it teaches`);
  }
  for (const f of listFiles(EXAMPLE_DIR, (n) => n.endsWith(".json") && n !== "catalog.json")) {
    const id = f.replace(/\.json$/, "");
    if (!EXAMPLES.some((e) => e.id === id)) problems.push(`example file ${f} is not listed in site/examples.mjs`);
  }

  // Sitemap lists only real pages and never the 404.
  const sitemap = join(out, "sitemap.xml");
  if (!existsSync(sitemap)) problems.push("sitemap.xml missing");
  else {
    for (const m of readFileSync(sitemap, "utf8").matchAll(/<loc>([^<]+)<\/loc>/g)) {
      const path = m[1].replace(SITE, "") || "/";
      if (!fileFor(out, path)) problems.push(`sitemap lists ${path}, which does not exist`);
    }
  }

  // Every token class the swatches use must exist in the stylesheet.
  const css = readFileSync(join(out, "assets", "tokens.css"), "utf8");
  for (const name of Object.keys(THEMES)) {
    for (const k of TOKENS) if (!css.includes(`.sw-${name}-${k}`)) problems.push(`tokens.css missing .sw-${name}-${k}`);
  }

  return { ok: problems.length === 0, problems, pages: files.length };
}

// ---------- command line ----------

function main(argv) {
  const check = argv.includes("--check");
  const outIdx = argv.indexOf("--out");
  if (check) {
    const out = mkdtempSync(join(tmpdir(), "p5loom-site-"));
    try {
      buildSite({ out });
      const result = checkSite(out);
      if (!result.ok) {
        console.error(`site check failed (${result.problems.length}):`);
        for (const p of result.problems) console.error(`  - ${p}`);
        process.exitCode = 1;
      } else {
        console.log(`site check passed: ${result.pages} pages, ${EXAMPLES.length} examples, links and CSP clean.`);
      }
    } finally {
      rmSync(out, { recursive: true, force: true });
    }
    return;
  }
  const out = resolve(root, outIdx >= 0 ? argv[outIdx + 1] : "dist");
  const built = buildSite({ out });
  const result = checkSite(out);
  console.log(`built ${built.pages.length} pages into ${relative(root, out) || out}`);
  if (!result.ok) {
    for (const p of result.problems) console.error(`  - ${p}`);
    process.exitCode = 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main(process.argv.slice(2));
