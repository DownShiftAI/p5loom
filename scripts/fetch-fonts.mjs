#!/usr/bin/env node
// Downloads the three typefaces the Dawnshift design uses and writes them into the site, so the site loads its fonts
// from its own origin (the Content-Security-Policy allows no other font host). Run once, then commit the output:
//   node scripts/fetch-fonts.mjs
// Faces (same as dawnshift.co): Urbanist for display, Hanken Grotesk for reading, IBM Plex Mono for labels and code.
// All three are licensed under the SIL Open Font License 1.1.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "..", "site", "assets", "fonts");
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const FACES = [
  { family: "Urbanist", query: "Urbanist:wght@400;500", file: "urbanist", weights: [400, 500] },
  { family: "Hanken Grotesk", query: "Hanken+Grotesk:wght@400", file: "hanken-grotesk", weights: [400] },
  { family: "IBM Plex Mono", query: "IBM+Plex+Mono:wght@400", file: "ibm-plex-mono", weights: [400] },
];

// The latin subset: the first @font-face block for each weight whose unicode-range covers basic Latin.
function latinBlocks(css) {
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
  return blocks
    .filter(([, subset]) => subset === "latin")
    .map(([, , body]) => ({
      weight: Number(/font-weight:\s*(\d+)/.exec(body)?.[1]),
      url: /src:\s*url\(([^)]+)\)/.exec(body)?.[1],
    }));
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  const rules = [];
  for (const face of FACES) {
    const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${face.query}&display=swap`, { headers: { "User-Agent": UA } })).text();
    for (const { weight, url } of latinBlocks(css)) {
      if (!url || !face.weights.includes(weight)) continue;
      const bytes = Buffer.from(await (await fetch(url)).arrayBuffer());
      const name = `${face.file}-${weight}.woff2`;
      writeFileSync(join(OUT, name), bytes);
      rules.push(
        `@font-face {\n  font-family: "${face.family}";\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url("/assets/fonts/${name}") format("woff2");\n}`,
      );
      console.log(`  ${name}  ${bytes.length} bytes`);
    }
  }
  writeFileSync(
    join(resolve(OUT, ".."), "fonts.css"),
    `/* Generated by scripts/fetch-fonts.mjs. Latin subsets, self-hosted. Licence: SIL Open Font License 1.1. */\n${rules.join("\n")}\n`,
  );
  console.log(`wrote ${rules.length} faces`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
